"""Generate docs/generated: the REST schema and the database schema (``chatlpt gen-docs``)."""

import json
from pathlib import Path

from pydantic import SecretStr

from chatlpt.config import Settings
from chatlpt.http import create_app
from chatlpt.runtime import Application
from chatlpt.store import schema
from chatlpt.testing import FixedClock, MemoryStore, PlainHasher, StaticPrices


def generate(out: Path, *, check: bool = False) -> list[str]:
    out.mkdir(parents=True, exist_ok=True)
    settings = Settings(session_secret=SecretStr("docs-only"), static_dir="/nonexistent")
    app = Application(
        settings,
        store=MemoryStore(),
        backend=None,
        clock=FixedClock(),
        hasher=PlainHasher(),
        prices=StaticPrices(),
        oauth={},
    )
    api = create_app(app, manage_lifecycle=False)
    spec = api.openapi()
    spec["info"]["version"] = "generated"
    files = {
        "openapi.json": json.dumps(spec, indent=2, sort_keys=True) + "\n",
        "db-schema.md": db_schema_markdown(),
    }
    stale: list[str] = []
    for name, content in files.items():
        path = out / name
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(name)
        else:
            path.write_text(content)
    return stale


def db_schema_markdown() -> str:
    lines = [
        "# Database schema",
        "",
        "Generated by `chatlpt gen-docs` from `chatlpt.store.schema`. Do not edit.",
        "",
    ]
    lines += ["## Entity relationship diagram", "", "```mermaid", "erDiagram"]
    for table in schema.metadata.sorted_tables:
        for fk in table.foreign_keys:
            lines.append(f"    {fk.column.table.name} ||--o{{ {table.name} : has")
    lines += ["```", ""]
    for table in schema.metadata.sorted_tables:
        lines += [
            f"## `{table.name}`",
            "",
            "| Column | Type | Nullable | Notes |",
            "| --- | --- | --- | --- |",
        ]
        for column in table.columns:
            notes = []
            if column.primary_key:
                notes.append("primary key")
            notes += [f"→ {fk.column.table.name}.{fk.column.name}" for fk in column.foreign_keys]
            nullable = "yes" if column.nullable else "no"
            lines.append(f"| `{column.name}` | {column.type} | {nullable} | {', '.join(notes)} |")
        lines.append("")
    return "\n".join(lines)
